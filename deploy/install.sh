#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")"
umask 077
mode="${1:---help}"
if [[ "${mode}" == --help ]]; then
  echo 'Usage: ./install.sh --prepare|--activate|--upgrade|--reinstall [--install-engine] [configuration arguments]'
  echo '--reinstall recreates application containers after backup; preserves database, files, accounts and authorization.'
  echo 'Prepare arguments: --public-url https://node.example.com --admin-email owner@example.com'
  echo 'Use activation.json (saved from the authority UI) with --activate. Never pass tokens in arguments.'
  exit 0
fi
shift
case "${mode}" in --prepare|--activate|--upgrade|--reinstall) ;; *) exit 1 ;; esac
exec 9>.installer.lock
flock -n 9 || { echo 'Another installer is active.' >&2; exit 1; }
if [[ "${1:-}" == --install-engine ]]; then
  bash ./install-engine.sh
  shift
fi
[[ "$(docker info --format '{{.OSType}}')" == linux ]] || { echo 'A Linux container engine is required.' >&2; exit 1; }
docker compose version >/dev/null
. ./linux-common.sh
assert_installation_owner
# This manifest is generated by the release packager, not downloaded from arbitrary input.
[[ -f images.env ]] || { echo 'Missing release image manifest.' >&2; exit 1; }
runtime_image="$(sed -n 's/^TRANSDOC_RUNTIME_IMAGE=//p' images.env)"
web_image="$(sed -n 's/^TRANSDOC_WEB_IMAGE=//p' images.env)"
pattern='^[a-zA-Z0-9./:_-]+@sha256:[a-f0-9]{64}$'
[[ "${runtime_image}" =~ ${pattern} && "${web_image}" =~ ${pattern} ]] || exit 1
install -d -m 700 config
machine_id="$(cat /etc/machine-id)"
docker pull "${runtime_image}"
if [[ "${mode}" == --prepare || "${mode}" == --activate ]]; then
  mount_args=()
  activation_args=()
  if [[ "${mode}" == --activate ]]; then
    [[ -f activation.json ]] || { echo 'Save the authority credential as activation.json first.' >&2; exit 1; }
    chmod 600 activation.json
    mount_args=(-v "${PWD}/activation.json:/activation.json:ro")
    activation_args=(--activation /activation.json)
  fi
  docker run --rm --user 0:0 -v "${PWD}/config:/config" "${mount_args[@]}" "${runtime_image}" \
    python -m packages.deployment_license.install_config --machine-id "${machine_id}" \
    --runtime-image "${runtime_image}" --web-image "${web_image}" "${activation_args[@]}" "$@"
fi
if [[ "${mode}" == --upgrade || "${mode}" == --reinstall ]]; then
  docker run --rm --user 0:0 -v "${PWD}/config:/config" "${runtime_image}" \
    python -m packages.deployment_license.install_origins
fi
export TRANSDOC_RUNTIME_IMAGE="${runtime_image}" TRANSDOC_WEB_IMAGE="${web_image}"
compose() { docker compose --env-file config/compose.env -f compose.yaml "$@"; }
compose config --quiet
if [[ "${mode}" == --prepare ]]; then
  compose pull postgres redis
  compose up -d --no-deps --wait --wait-timeout 180 postgres redis
  echo 'PostgreSQL and Redis are ready; no application processors have started.'
  echo 'Save the authority credential as activation.json here, then run --activate. Saved URL, port and operator settings are retained.'
  exit 0
fi
[[ -f config/activation.token && -f config/authority-public.pem ]] || { echo 'Activation required.' >&2; exit 1; }
# Pull before touching active services; source code is not needed on the target host.
compose pull
compose stop --timeout 30 dispatcher
compose stop --timeout -1 worker
compose up -d --wait --wait-timeout 180 postgres redis
install -d -m 700 backups
compose run --rm --no-deps -e "BACKUP_FILE=pre-upgrade-$(date -u +%Y%m%dT%H%M%SZ).dump" backup
compose run --rm --no-deps storage-init
compose run --rm --no-deps migrate
if [[ -f config/bootstrap.json ]]; then
  compose run --rm --no-deps -v "${PWD}/config/bootstrap.json:/run/bootstrap.json:ro" api \
    python -m services.api.src.modules.deployment_licenses.bootstrap --file /run/bootstrap.json
fi
# Credential writes are atomic replacements; recreate file bind mounts to see the new inode.
compose up -d --no-deps --force-recreate license-agent
recreate=()
if [[ "${mode}" == --reinstall ]]; then recreate=(--force-recreate); fi
compose up -d --no-deps "${recreate[@]}" --wait --wait-timeout 180 api
compose up -d --no-deps --force-recreate --wait --wait-timeout 180 web
compose exec -T api python -m packages.deployment_license.wait_ready
compose up -d --no-deps "${recreate[@]}" worker dispatcher
docker run --rm --user 0:0 -v "${PWD}/config:/config" "${runtime_image}" \
  python -m packages.deployment_license.pin_release --runtime-image "${runtime_image}" --web-image "${web_image}"
if ! compose exec -T license-agent python -m services.api.src.modules.deployment_licenses.node_agent --once; then
  echo 'Application ready; authority profile/version sync is pending. Retry manual sync later.'
fi
echo 'Deployment ready. Read config/bootstrap.json privately for the initial password; change it after login. No existing passwords were reset.'
